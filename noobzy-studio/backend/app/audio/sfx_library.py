"""The Sound Library: a catalog of locally-synthesized AudioAssets.

Every asset here is generated by app.audio.sfx (NumPy, offline, no network,
no third-party license). Nothing is bundled from an external sound pack
because we could not verify redistribution rights for one in this
environment -- per the spec, when redistribution is unclear we do NOT bundle
assets. These procedural assets sidestep that problem entirely: their
license is "we generated the waveform."
"""
from __future__ import annotations

from pathlib import Path

from app.schemas import AudioAsset, AudioAssetLicense, SoundCueCategory
from app.media.ffprobe_util import probe
from . import sfx


def build_and_register_library(assets_dir: str | Path) -> list[AudioAsset]:
    paths = sfx.render_all(assets_dir)
    assets = []
    for name, path in paths.items():
        duration = probe_wav_duration(path)
        assets.append(
            AudioAsset(
                id=f"asset_{name}",
                name=name,
                file_path=str(path),
                duration_sec=duration,
                license=AudioAssetLicense.procedurally_generated,
                source="noobzy-procedural-synth (NumPy sine/sweep/noise, generated locally)",
                attribution_required=False,
                tags=[name],
            )
        )
    return assets


def probe_wav_duration(path: str | Path) -> float:
    import wave
    with wave.open(str(path), "rb") as w:
        return w.getnframes() / float(w.getframerate())


def build_music_loop(out_path: str | Path, duration_s: float = 20.0) -> AudioAsset:
    """A simple procedurally generated ambient pad+arpeggio loop.

    Deliberately NOT a real song: a slow pad chord plus a soft arpeggio,
    synthesized locally so there is zero copyright risk. Clearly a
    placeholder background track, not a licensed music bed.
    """
    import numpy as np
    import wave

    sr = sfx.SR
    t = np.linspace(0, duration_s, int(sr * duration_s), endpoint=False)
    chord = [220.0, 277.18, 329.63]  # A minor-ish triad
    pad = sum(np.sin(2 * np.pi * f * t) for f in chord) / len(chord)
    pad *= 0.25

    # Soft arpeggio on top, looping every 2s
    arp_freqs = [440.0, 523.25, 659.25, 523.25]
    arp = np.zeros_like(t)
    note_len = 0.5
    n_per_note = int(sr * note_len)
    for i in range(0, len(t), n_per_note):
        f = arp_freqs[(i // n_per_note) % len(arp_freqs)]
        seg = t[i : i + n_per_note] - t[i]
        env = np.exp(-seg * 2.5)
        arp[i : i + len(seg)] = np.sin(2 * np.pi * f * seg) * env * 0.15

    sig = pad + arp
    m = max(abs(sig.max()), abs(sig.min()))
    if m > 1e-9:
        sig = sig * (0.7 / m)

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    pcm16 = (np.clip(sig, -1, 1) * 32767).astype(np.int16)
    with wave.open(str(out_path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(pcm16.tobytes())

    return AudioAsset(
        id="asset_music_loop_signature",
        name="noobzy_signature_pad_loop",
        category=None,
        file_path=str(out_path),
        duration_sec=duration_s,
        license=AudioAssetLicense.procedurally_generated,
        source="noobzy-procedural-synth (generated pad+arpeggio, no copyrighted music)",
        attribution_required=False,
        tags=["music", "signature-theme"],
    )
